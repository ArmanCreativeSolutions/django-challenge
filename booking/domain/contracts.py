from contextlib import AbstractContextManager
from datetime import datetime
from decimal import Decimal
from typing import Protocol
from uuid import UUID

from shared.contracts import Page, PageRequest

from .data_objects import MatchData, ReplayData, SeatData, SeatDefinition, StadiumData, TicketData


class BuyerRepository(Protocol):
    def lock_active(self, user_id: int) -> bool: ...


class StadiumRepository(Protocol):
    def list(self, page: PageRequest) -> Page[StadiumData]: ...

    def get(self, stadium_id: int) -> StadiumData | None: ...

    def create(self, *, name: str, address: str) -> StadiumData: ...

    def get_or_create(self, *, name: str, address: str) -> StadiumData: ...


class MatchRepository(Protocol):
    def list(self, page: PageRequest, *, include_drafts: bool) -> Page[MatchData]: ...

    def get(self, match_id: int, *, for_update: bool = False) -> MatchData | None: ...

    def create(
        self, *, stadium: int, home_team: str, away_team: str, starts_at: datetime
    ) -> MatchData: ...

    def publish(self, match_id: int) -> MatchData: ...

    def find_upcoming(
        self, *, stadium: int, home_team: str, away_team: str, now: datetime
    ) -> MatchData | None: ...


class SeatRepository(Protocol):
    def lock(self, *, match_id: int, seat_id: int) -> SeatData | None: ...

    def exists_for_match(self, match_id: int) -> bool: ...

    def replace(self, match_id: int, seats: list[SeatDefinition]) -> None: ...

    def availability(self, match_id: int) -> list[dict]: ...


class TicketRepository(Protocol):
    def exists_for_buyer(self, *, user_id: int, match_id: int) -> bool: ...

    def exists_for_seat(self, seat_id: int) -> bool: ...

    def create(
        self, *, user_id: int, match_id: int, seat_id: int, price: Decimal
    ) -> TicketData: ...

    def list_for_buyer(self, user_id: int, page: PageRequest) -> Page[TicketData]: ...

    def get_for_buyer(self, user_id: int, ticket_id: UUID) -> TicketData | None: ...


class ReplayRepository(Protocol):
    def get(self, user_id: int, key: str) -> ReplayData | None: ...

    def create(self, user_id: int, key: str, record: ReplayData) -> None: ...


class SeatMapCache(Protocol):
    def get(self, match_id: int) -> dict | None: ...

    def set(self, match_id: int, snapshot: dict) -> None: ...

    def filling(self, match_id: int) -> AbstractContextManager[None]: ...

    def invalidate(self, match_id: int) -> None: ...
